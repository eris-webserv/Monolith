using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.MassFabricator;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Mono.MassFabricator;

[GenerateTypedNameReferences]
public sealed partial class MassFabricatorMenu : RadialMenu
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IEntityManager _entities = default!;

    public event Action<ProtoId<MassFabricatorBlueprintPrototype>?, string?, MassFabricatorEraseMode>? Selected;

    public MassFabricatorMenu()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    public void Populate(MassFabricatorComponent fabricator)
    {
        var sprites = _entities.System<SpriteSystem>();
        var choices = new List<(MassFabricatorBlueprintPrototype Blueprint, string Name, string Target, SpriteSpecifier? Icon)>();
        foreach (var id in fabricator.AvailableBlueprints)
        {
            if (!_prototypes.TryIndex(id, out var blueprint))
                continue;

            if (blueprint.Variants.Count == 0 && blueprint.Target is { } target)
                choices.Add((blueprint, blueprint.Name, target, blueprint.Sprite));
            else
                foreach (var variant in blueprint.Variants)
                    choices.Add((blueprint, variant.Name, variant.Target, variant.Sprite));
        }

        foreach (var group in choices.GroupBy(choice => (choice.Blueprint.Category, choice.Blueprint.Subcategory)))
        {
            var category = FindControl<RadialContainer>(group.Key.Category.ToString());
            if (category == null)
                continue;

            RadialContainer destination = category;
            if (group.Count() > 1)
            {
                var groupName = group.Key.Category + "_" + group.Key.Subcategory;
                destination = new RadialContainer
                {
                    Name = groupName,
                    VerticalExpand = true,
                    HorizontalExpand = true,
                    InitialRadius = group.Key.Subcategory == "Stairs" ? 180 : 100,
                };
                AddChild(destination);
                var groupButton = Button(group.Key.Subcategory, groupName,
                    showLabel: group.Key.Subcategory != "Stairs");
                if (group.Key.Subcategory == "Stairs")
                    groupButton.AddChild(new TextureRect
                    {
                        Texture = sprites.GetPrototypeIcon("CEZLevelLadderStone").Default,
                        TextureScale = new Vector2(1.5f, 1.5f),
                        VerticalAlignment = VAlignment.Center,
                        HorizontalAlignment = HAlignment.Center,
                    });
                category.AddChild(groupButton);
            }

            foreach (var choice in group)
            {
                var texture = choice.Icon != null ? sprites.Frame0(choice.Icon) :
                    choice.Blueprint.Kind == MassFabricatorBlueprintKind.Entity &&
                    _prototypes.TryIndex<EntityPrototype>(choice.Target, out var entity)
                        ? sprites.GetPrototypeIcon(entity).Default : null;
                var button = Button(choice.Name, showLabel: texture == null);
                if (texture != null)
                {
                    button.AddChild(new TextureRect
                    {
                        Texture = texture,
                        TextureScale = new Vector2(2f, 2f),
                        VerticalAlignment = VAlignment.Center,
                        HorizontalAlignment = HAlignment.Center,
                    });
                }
                button.OnButtonUp += _ => Choose(choice.Blueprint.ID, choice.Target, MassFabricatorEraseMode.None);
                destination.AddChild(button);
            }
        }

        EraseButton.OnButtonUp += _ => Choose(null, null, MassFabricatorEraseMode.Single);
    }

    private RadialMenuTextureButtonWithSector Button(string name, string? layer = null, bool showLabel = true)
    {
        var button = new RadialMenuTextureButtonWithSector
        {
            SetSize = new Vector2(64f, 64f),
            ToolTip = name,
        };
        if (layer != null)
            button.TargetLayer = layer;
        if (showLabel)
            button.AddChild(new Label { Text = name, HorizontalAlignment = HAlignment.Center, VerticalAlignment = VAlignment.Center });
        return button;
    }

    private void Choose(ProtoId<MassFabricatorBlueprintPrototype>? blueprint, string? target, MassFabricatorEraseMode erase)
    {
        Selected?.Invoke(blueprint, target, erase);
        Close();
    }
}
