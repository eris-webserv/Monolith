using System.Linq;
using System.Numerics;
using Content.Shared.Materials;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.Graphics;
using Robust.Shared.Input;
using Robust.Shared.Prototypes;

namespace Content.Client._Mono.MassFabricator;

[GenerateTypedNameReferences]
public sealed partial class MassFabricatorScreen : UIScreen
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IEntityManager _entities = default!;

    private static readonly Color BlueprintBlue = Color.FromHex("#379DFF");
    private static readonly Color BlueprintRed = Color.FromHex("#FF3B3B");
    private readonly StyleBoxFlat _blueprintFill = new(BlueprintBlue);
    private string _bufferState = string.Empty;

    public MassFabricatorScreen()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        SetAnchorPreset(ViewportContainer, LayoutPreset.Wide);
        SetAnchorPreset(MainViewport, LayoutPreset.Wide);
        SetAnchorAndMarginPreset(StatusBars, LayoutPreset.TopRight, margin: 12);
        BlueprintBar.ForegroundStyleBoxOverride = _blueprintFill;
        MaterialBar.PanelOverride = new StyleBoxFlat(Color.FromHex("#202025"));
        MaterialBar.ToolTip = Loc.GetString("mass-fabricator-buffer-hint");
        CloseMaterials.OnPressed += _ => MaterialDetails.Visible = false;
        MaterialBar.OnKeyBindDown += args =>
        {
            if (args.Function != EngineKeyFunctions.UseSecondary)
                return;

            args.Handle();
            MaterialDetails.Visible = !MaterialDetails.Visible;
        };
    }

    public void UpdateBars(float blueprintLoad, Dictionary<ProtoId<MaterialPrototype>, int> materials,
        Dictionary<string, int> available, int capacity)
    {
        BlueprintBar.Value = Math.Clamp(blueprintLoad, 0f, 1f);
        _blueprintFill.BackgroundColor = Color.InterpolateBetween(BlueprintBlue, BlueprintRed,
            Math.Clamp((blueprintLoad - 0.75f) * 4f, 0f, 1f));

        var state = $"{capacity}:" + string.Join(';', materials.OrderBy(pair => pair.Key.Id)
            .Select(pair => $"{pair.Key}:{pair.Value}:{available.GetValueOrDefault(pair.Key.Id)}"));
        if (state == _bufferState)
            return;
        _bufferState = state;
        MaterialSegments.Segments.Clear();
        MaterialSegments.Capacity = capacity;
        MaterialRows.RemoveAllChildren();
        var sprites = _entities.System<SpriteSystem>();
        BufferTotal.Text = Loc.GetString("mass-fabricator-buffer-total",
            ("stored", materials.Values.Sum()), ("capacity", capacity));
        foreach (var (id, amount) in materials.OrderBy(pair => pair.Key.Id))
        {
            var material = _prototypes.Index(id);
            var name = Loc.GetString("mass-fabricator-display-name", ("name", Loc.GetString(material.Name)));
            var entry = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical };
            var row = new BoxContainer { SeparationOverride = 6 };
            row.AddChild(new TextureRect
            {
                Texture = material.StackEntity is { } stack
                    ? sprites.GetPrototypeIcon(stack).Default : sprites.Frame0(material.Icon),
                SetSize = new Vector2(24),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
            });
            row.AddChild(new Label { Text = name, HorizontalExpand = true });
            row.AddChild(new Label { Text = $"{amount:N0}" });
            entry.AddChild(row);
            var reserved = amount - available.GetValueOrDefault(id.Id);
            if (reserved > 0)
                entry.AddChild(new Label
                {
                    Text = Loc.GetString("mass-fabricator-buffer-reserved", ("amount", reserved)),
                    FontColorOverride = Color.Gray,
                    Margin = new Thickness(30, 0, 0, 0),
                });
            MaterialRows.AddChild(entry);
            if (amount > 0)
                MaterialSegments.Segments.Add((material.Color, amount));
        }
    }
}
