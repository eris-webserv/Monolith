using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Client.Graphics;

namespace Content.Client._Mono.MassFabricator;

[GenerateTypedNameReferences]
public sealed partial class MassFabricatorScreen : UIScreen
{
    private static readonly Color BlueprintBlue = Color.FromHex("#379DFF");
    private static readonly Color BlueprintRed = Color.FromHex("#FF3B3B");
    private readonly StyleBoxFlat _blueprintFill = new(BlueprintBlue);

    public MassFabricatorScreen()
    {
        RobustXamlLoader.Load(this);
        SetAnchorPreset(ViewportContainer, LayoutPreset.Wide);
        SetAnchorPreset(MainViewport, LayoutPreset.Wide);
        SetAnchorAndMarginPreset(StatusBars, LayoutPreset.TopRight, margin: 12);
        BlueprintBar.ForegroundStyleBoxOverride = _blueprintFill;
        ChargeBar.ForegroundStyleBoxOverride = new StyleBoxFlat(Color.FromHex("#F3CA4B"));
    }

    public void UpdateBars(float blueprintLoad, float remainingCharge)
    {
        BlueprintBar.Value = Math.Clamp(blueprintLoad, 0f, 1f);
        _blueprintFill.BackgroundColor = Color.InterpolateBetween(BlueprintBlue, BlueprintRed,
            Math.Clamp((blueprintLoad - 0.75f) * 4f, 0f, 1f));
        ChargeBar.Value = Math.Clamp(remainingCharge, 0f, 1f);
    }
}
