    public void UpdateState(NavInterfaceState state)
    {
        EnsureRadarModeButtons();
        ApplyRadarModeDefaults();
        SetMatrix(EntManager.GetCoordinates(state.Coordinates), state.Angle);

        WorldMaxRange = state.MaxRange;

        if (WorldMaxRange < WorldRange)
        {
            ActualRadarRange = WorldMaxRange;
        }

        if (WorldMaxRange < WorldMinRange)
            WorldMinRange = WorldMaxRange;

        ActualRadarRange = Math.Clamp(ActualRadarRange, WorldMinRange, WorldMaxRange);

        // Frontier
        if (state.MaxIffRange != null)
            MaximumIFFDistance = state.MaxIffRange.Value;
        HideCoords = state.HideCoords;
        // End Frontier

        _docks = state.Docks;

        NfUpdateState(state); // Frontier Update State
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        DrawBacking(handle);
        DrawCircles(handle);

        // No data
        if (_coordinates == null || _rotation == null)
        {
            return;
        }

        var xformQuery = EntManager.GetEntityQuery<TransformComponent>();
        var fixturesQuery = EntManager.GetEntityQuery<FixturesComponent>();
        var bodyQuery = EntManager.GetEntityQuery<PhysicsComponent>();

        if (!xformQuery.TryGetComponent(_coordinates.Value.EntityId, out var xform)
            || xform.MapID == MapId.Nullspace)
        {
            return;
        }

        // Mono
        if (EntManager.TryGetComponent<RadarConsoleComponent>(_consoleEntity, out var radar))
        {
            Draggable = radar.Pannable;
        }
        // Mono - TODO: remove _rotation and make it a method instead
        var coordEnt = _coordinates.Value.EntityId;
        var coordEntRot = _transform.GetWorldRotation(coordEnt);
        if (_angleFollow && EntManager.TryGetComponent<TransformComponent>(coordEnt, out var coordXform))
            _rotation = coordEntRot;
        else
            _rotation = Angle.Zero;

        var worldRot = _rotation.Value;
        var mapPos = _transform.ToMapCoordinates(_coordinates.Value).Offset(_rotation.Value.RotateVec(Offset));
        var mapCoord = _transform.ToCoordinates(mapPos);
        var worldToShuttle = Matrix3Helpers.CreateTranslation(-mapCoord.Position) * Matrix3Helpers.CreateRotation(-worldRot);
        Matrix3x2.Invert(worldToShuttle, out var shuttleToWorld);
        var shuttleToView = Matrix3x2.CreateScale(new Vector2(MinimapScale, -MinimapScale)) * Matrix3x2.CreateTranslation(MidPointVector);
        var worldToView = worldToShuttle * shuttleToView;

        // Frontier Corvax: north line drawing
        DrawNorthLine(handle, worldRot);

        // Mono
        switch (_azimuthMode)
        {
            case RadarAzimuthMode.Edge:
                DrawAzimuthScale(handle, worldRot);
                break;
            case RadarAzimuthMode.Ring:
                DrawAzimuthRing(handle, worldRot);
                break;
        }

        if (worldRot != Angle.Zero)
        {
            DrawCompassOverlay(handle, coordEntRot);
        }

        // CE: planets render under grids, shields, docks and blips.
        DrawPlanets(handle, xform.MapID, mapPos.Position, worldToView);

        // Draw shields (over planets, under our grid detail)
        DrawShields(handle, xform, worldToShuttle);

        // Draw our grid in detail
        var ourGridId = xform.GridUid;
        if (EntManager.TryGetComponent<MapGridComponent>(ourGridId, out var ourGrid) &&
            fixturesQuery.HasComponent(ourGridId.Value))
        {
            var ourGridToWorld = _transform.GetWorldMatrix(ourGridId.Value);
            var ourGridToShuttle = Matrix3x2.Multiply(ourGridToWorld, worldToShuttle);
            var ourGridToView = ourGridToShuttle * shuttleToView;
            var color = _shuttles.GetIFFColor(ourGridId.Value, self: true);

            DrawGrid(handle, ourGridToView, (ourGridId.Value, ourGrid), color);
            DrawDocks(handle, ourGridId.Value, ourGridToView);
        }

        // Draw radar position on the station
        // Mono - use precalculated verts and scale each point rather than allocating a fresh array
        var radarPosVerts = new Vector2[RadarPosVertsCache.Length];
        for (var i = 0; i < radarPosVerts.Length; i++)
        {
            radarPosVerts[i] = ScalePosition(RadarPosVertsCache[i]);
        }

        handle.DrawPrimitives(DrawPrimitiveTopology.TriangleFan, radarPosVerts, Color.Lime);

        var viewBounds = new Box2Rotated(new Box2(-WorldRange, -WorldRange, WorldRange, WorldRange).Translated(mapPos.Position), worldRot, mapPos.Position);
        var viewAABB = viewBounds.CalcBoundingBox();

        _grids.Clear();
        _mapManager.FindGridsIntersecting(xform.MapID, new Box2(mapPos.Position - MaxRadarRangeVector, mapPos.Position + MaxRadarRangeVector), ref _grids, approx: true, includeMap: false);

        // CE: gather grids on vertically adjacent maps (neighbouring z-levels and
        // transit gaps). Z-maps share XY coordinate space, so the same query box works.
        _drawGrids.Clear();
        foreach (var sameLayerGrid in _grids)
        {
            _drawGrids.Add((sameLayerGrid, 0));
        }

        _adjacentZMaps.Clear();
        var ourMapUid = _mapManager.GetMapEntityId(xform.MapID);
        if (ourMapUid.IsValid())
            _zLevels.GetAdjacentRenderMaps(ourMapUid, _adjacentZMaps);

        foreach (var (adjMapUid, zMapDir) in _adjacentZMaps)
        {
            if (!EntManager.TryGetComponent(adjMapUid, out MapComponent? adjMapComp))
                continue;

            _offLayerGrids.Clear();
            _mapManager.FindGridsIntersecting(adjMapComp.MapId, new Box2(mapPos.Position - MaxRadarRangeVector, mapPos.Position + MaxRadarRangeVector), ref _offLayerGrids, approx: true, includeMap: false);

            foreach (var offGrid in _offLayerGrids)
            {
                _drawGrids.Add((offGrid, zMapDir));
            }
        }
        // CE: viewer's continuous altitude (level depth + transit progress + airborne
        // offset) so off-layer ghosting can fade with actual vertical separation.
        var ourAltitude = _zLevels.GetAbsoluteAltitude(coordEnt);
        // End CE

        // Mono edited: Frontier - collect blip location data outside foreach - more changes ahead
        _tempBlipDataList.Clear();

