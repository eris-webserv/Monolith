            if (shouldDrawIFF)
            {
                if (IFFFilter != null)
                    shouldDrawIFF &= IFFFilter(gUid, grid.Comp, iff, hideLabel, labelName!);
                if (isPlayerShuttle)
                    shouldDrawIFF &= ShowIFFShuttles;
